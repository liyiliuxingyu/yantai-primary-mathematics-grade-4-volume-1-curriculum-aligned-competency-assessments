"""Recover the A4 base and the exact scan background from a concise release.

Only the top-level Forms identified by receipt.bands are copied back.  Importing
an entire long page with a clip would retain all its other translated bands in
the resource tree; those hidden images make a later get_image_rects() unsafe.
Isolating the original band also omits every new note, including notes painted
over reused blank space, without painting an artificial white rectangle.

The separate pure-source PDF is rebuilt from the original image bytes, their
SHA-256 values and their exact A4 rectangles, never from inferred long-page
image locations.  It is suitable for the builder's pointer/duplicate/patch
background restoration.  This script requires a complete 128-page publication.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path

import fitz


ROOT = Path(__file__).resolve().parent
GEOMETRY_TOLERANCE = 0.002


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rect_close(a, b, tolerance=GEOMETRY_TOLERANCE):
    return max(abs(x - y) for x, y in zip(a, b)) <= tolerance


def top_level_forms(page):
    """Return painted Form bounds in the page's top-left coordinates."""
    result = []
    transform = page.transformation_matrix
    for xref, name, invoker, bbox in page.get_xobjects():
        if invoker:
            continue
        result.append({"xref": xref, "name": name,
                       "rect": list(fitz.Rect(bbox) * transform)})
    return result


def match_form(page, target_rect, tolerance=GEOMETRY_TOLERANCE):
    matches = [f for f in top_level_forms(page)
               if rect_close(f["rect"], target_rect, tolerance)]
    if len(matches) != 1:
        raise ValueError(
            f"Expected one original Form at {target_rect}, found {len(matches)} "
            f"on publication page {page.number + 1}.")
    return matches[0]


def isolated_form_page(container, original_page, name):
    """Paint one original root Form on a distinct temporary source page.

    A distinct page number is important: show_pdf_page caches imported source
    pages and must never reuse an earlier page after its contents were changed.
    The temporary page's Resources contains only that one root Form.  This also
    prevents unused note Forms and other translated bands being grafted into
    the recovered file at all.
    """
    roots = [x for x in original_page.get_xobjects()
             if x[1] == name and x[2] == 0]
    if len(roots) != 1:
        raise ValueError("Original publication Form is missing or ambiguous.")
    page = container.new_page(width=original_page.rect.width,
                              height=original_page.rect.height)
    stream_xref = container.get_new_xref()
    container.update_object(stream_xref, "<<>>")
    # Names generated by show_pdf_page are plain ASCII fzFrm identifiers.
    if not name.isascii() or not name.replace("_", "").isalnum():
        raise ValueError(f"Unsupported PDF resource name: {name!r}")
    container.xref_set_key(page.xref, "Resources",
                           f"<< /XObject << /{name} {roots[0][0]} 0 R >> >>")
    container.update_stream(stream_xref, f"q /{name} Do Q".encode("ascii"))
    page.set_contents(stream_xref)
    return page.number


def coalesced_a4_page(container, forms):
    """Import the shared A4 source Form once after validating every band.

    The publisher's original bands all reference the same 595x841 source Form.
    Reusing it once avoids clip-edge rasterization differences which otherwise
    change a later empty-row measurement by half a point.  This is lossless
    coalescing of the validated bands, not a screenshot or inferred white fill.
    """
    refs = set()
    for form in forms:
        kind, value = container.xref_get_key(
            form["xref"], "Resources/XObject/fullpage")
        if kind != "xref":
            raise ValueError("Original band does not retain its A4 source Form.")
        refs.add(int(value.split()[0]))
    if len(refs) != 1:
        raise ValueError("Original bands do not share one unmodified A4 source Form.")
    xref = refs.pop()
    kind, bbox = container.xref_get_key(xref, "BBox")
    values = [float(x) for x in re.findall(r"[-+]?\d*\.?\d+(?:[Ee][-+]?\d+)?", bbox)]
    if kind != "array" or len(values) != 4 or not rect_close(values, [0, 0, 595, 841]):
        raise ValueError("Shared original Form is not exactly A4-sized.")
    kind, matrix = container.xref_get_key(xref, "Matrix")
    if kind != "null":
        values = [float(x) for x in re.findall(r"[-+]?\d*\.?\d+(?:[Ee][-+]?\d+)?", matrix)]
        if len(values) != 6 or not rect_close(values, [1, 0, 0, 1, 0, 0]):
            raise ValueError("Shared original Form has a nonidentity transform.")
    page = container.new_page(width=595, height=841)
    container.xref_set_key(page.xref, "Resources",
                           f"<< /XObject << /RecoveredA4 {xref} 0 R >> >>")
    content = container.get_new_xref()
    container.update_object(content, "<<>>")
    container.update_stream(content, b"q /RecoveredA4 Do Q")
    page.set_contents(content)
    return page.number


def original_image_bytes(source, required_hashes):
    """Read each original JPEG once, including nested Form resources."""
    found = {}
    visited = set()
    for page in source:
        for image in page.get_images(full=True):
            xref = image[0]
            if xref in visited:
                continue
            visited.add(xref)
            extracted = source.extract_image(xref)
            raw = extracted["image"]
            digest = hashlib.sha256(raw).hexdigest()
            if digest in required_hashes:
                if extracted["ext"] not in {"jpeg", "jpg"}:
                    raise ValueError(f"Original scan {digest} is not a JPEG.")
                found[digest] = raw
    missing = sorted(required_hashes - found.keys())
    if missing:
        raise ValueError(f"Publication is missing {len(missing)} original JPEGs: "
                         + ", ".join(missing[:5]))
    return found


def make_pure_source(source, entries):
    required = {e["sha256"] for e in entries}
    raw_by_hash = original_image_bytes(source, required)
    by_page = defaultdict(list)
    # A repeated original image at the same rectangle is one scan placement.
    seen = set()
    for e in entries:
        signature = (e["base_page"], e["sha256"], tuple(e["rect"]))
        if signature not in seen:
            seen.add(signature)
            by_page[e["base_page"]].append(e)
    pure = fitz.open()
    for page_number in range(1, 129):
        page = pure.new_page(width=595, height=841)
        for e in by_page[page_number]:
            page.insert_image(fitz.Rect(e["rect"]),
                              stream=raw_by_hash[e["sha256"]],
                              keep_proportion=False)
    return pure, by_page


def validate_receipt(receipt, source):
    if len(source) != 128 or not receipt.get("first_page_blank"):
        raise ValueError("Recovery requires the full 128-page published release.")
    mapping = {m["book_page"]: m for m in receipt["mapping"]}
    if set(mapping) != set(range(1, 109)):
        raise ValueError("Receipt must contain all original book pages 1–108.")
    by_book = defaultdict(list)
    for band in receipt["bands"]:
        by_book[band["book_page"]].append(band)
    for book, m in mapping.items():
        expected_y = 0.0
        for band in by_book[book]:
            sr, tr = map(fitz.Rect, (band["source_rect"], band["target_rect"]))
            if not rect_close([sr.width, sr.height], [tr.width, tr.height]):
                raise ValueError(f"Book page {book} band is not at 1:1 scale.")
            if not rect_close([sr.x0, sr.x1, sr.y0], [0, 595, expected_y]):
                raise ValueError(f"Book page {book} has a missing/overlapping band.")
            if band["pdf_page"] != m["answer_pdf_page"]:
                raise ValueError(f"Book page {book} has inconsistent page mapping.")
            expected_y = sr.y1
        if abs(expected_y - 841) > GEOMETRY_TOLERANCE:
            raise ValueError(f"Book page {book} bands do not cover 0–841.")
    return mapping, by_book


def verify_image_geometry(doc, by_page):
    """Detect the hidden-offset-image failure instead of blindly accepting it."""
    failures = []
    maximum_error = 0.0
    placement_count = 0
    for page_number, page in enumerate(doc, 1):
        expected = by_page[page_number]
        hashes = {}
        seen = set()
        expected_hashes = {e["sha256"] for e in expected}
        # This release has one original JPEG per nonblank page.  In that case
        # associate its exact compressed-byte hash with all paint placements,
        # without decoding the multi-megapixel JPEG for every repeated band.
        # A more general multi-image page uses MuPDF's xref association instead.
        single_original = len(expected_hashes) <= 1
        if single_original:
            resource_hashes = set()
            for image in page.get_images(full=True):
                xref = image[0]
                if xref not in hashes:
                    hashes[xref] = hashlib.sha256(
                        doc.extract_image(xref)["image"]).hexdigest()
                resource_hashes.add(hashes[xref])
            if resource_hashes != expected_hashes:
                failures.append({"base_page": page_number,
                                 "reason": "Original JPEG resources differ.",
                                 "found_sha256": sorted(resource_hashes)})
        # One lightweight display-list traversal detects every painted image,
        # including incorrectly translated bands hidden behind an outer clip.
        for image in page.get_image_info(xrefs=not single_original):
            if single_original:
                digest = next(iter(expected_hashes), "")
            else:
                xref = image["xref"]
                if not xref:
                    failures.append({"base_page": page_number,
                                     "reason": "Unregistered inline image."})
                    continue
                if xref not in hashes:
                    hashes[xref] = hashlib.sha256(
                        doc.extract_image(xref)["image"]).hexdigest()
                digest = hashes[xref]
            rect = fitz.Rect(image["bbox"])
            if not rect.intersects(page.rect):
                continue
            seen.add(digest)
            candidates = [e for e in expected if e["sha256"] == digest]
            error = min((max(abs(a-b) for a, b in zip(rect, e["rect"]))
                         for e in candidates), default=float("inf"))
            maximum_error = max(maximum_error, error)
            placement_count += 1
            if error > GEOMETRY_TOLERANCE:
                failures.append({"base_page": page_number, "sha256": digest,
                                 "rect": list(rect), "maximum_error_pt": error})
        missing = {e["sha256"] for e in expected} - seen
        if missing:
            failures.append({"base_page": page_number,
                             "reason": "Missing original image placement.",
                             "missing_sha256": sorted(missing)})
    if failures:
        raise ValueError("Unsafe recovered image geometry: "
                         + json.dumps(failures[:5], ensure_ascii=False))
    return {"effective_image_placements": placement_count,
            "maximum_image_position_error_pt": maximum_error,
            "hidden_offset_images": 0}


def recover(answer_pdf, receipt_path, output, pure_output, report_path,
            verify_hash=True):
    if len({answer_pdf.resolve(), output.resolve(), pure_output.resolve()}) != 3:
        raise ValueError("Publication, recovered base and pure source must use distinct paths.")
    receipt = json.loads(receipt_path.read_text())
    source_hash = sha256(answer_pdf)
    if verify_hash and source_hash != receipt.get("sha256"):
        raise ValueError("Publication SHA-256 does not match the selected receipt.")
    source = fitz.open(answer_pdf)
    mapping, bands = validate_receipt(receipt, source)
    pure, image_registry = make_pure_source(source,
                                           receipt["source_original_images"])
    footers = {f["book_page"]: f for f in receipt["moved_footers"]}
    if set(footers) != set(mapping):
        raise ValueError("Receipt must retain the moved footer of every book page.")
    out = fitz.open()
    out.insert_pdf(source, from_page=0, to_page=3)
    form_checks = []
    for book in range(1, 109):
        m = mapping[book]
        original = source[m["answer_pdf_page"] - 1]
        container = fitz.open()
        container.insert_pdf(source, from_page=original.number,
                             to_page=original.number)
        # Adding temporary pages invalidates existing Page wrappers; reload page
        # zero on every iteration rather than retaining an orphaned wrapper.
        page = out.new_page(width=595, height=841)
        original_forms = []
        for band in bands[book]:
            form = match_form(container[0], band["target_rect"])
            original_forms.append(form)
            form_checks.append({"book_page": book,
                                "source_rect": band["source_rect"],
                                "target_rect": band["target_rect"],
                                "publication_form": form["name"]})
        temp_number = coalesced_a4_page(container, original_forms)
        page.show_pdf_page(fitz.Rect(0, 0, 595, 841), container, temp_number,
                           keep_proportion=False)
        footer = footers[book]
        if book in {f['book_page']for f in receipt.get('footer_overrides',[])}:
            rr=fitz.Rect(footer['source_rect'])
            page.show_pdf_page(rr,pure,book+3,clip=rr,keep_proportion=False)
        else:
            form = match_form(container[0], footer["target_rect"])
            temp_number = isolated_form_page(container, container[0], form["name"])
            page.show_pdf_page(fitz.Rect(footer["source_rect"]), container, temp_number,
                               clip=fitz.Rect(footer["target_rect"]),keep_proportion=False)
        for h in receipt.get('moved_headings',[]):
            if h['book_page']!=book:continue
            form=match_form(container[0],h['target_rect'],tolerance=.01)
            temp_number=isolated_form_page(container,container[0],form['name'])
            page.show_pdf_page(fitz.Rect(h['source_rect']),container,temp_number,
                               clip=fitz.Rect(form['rect']),keep_proportion=False)
        container.close()
    out.insert_pdf(source, from_page=112, to_page=127)
    assert len(out) == 128
    output.parent.mkdir(parents=True, exist_ok=True)
    pure_output.parent.mkdir(parents=True, exist_ok=True)
    output_tmp = output.with_name(output.stem + ".recovery.tmp.pdf")
    pure_tmp = pure_output.with_name(pure_output.stem + ".recovery.tmp.pdf")
    out.save(output_tmp, garbage=4, deflate=True)
    pure.save(pure_tmp, garbage=4, deflate=True)
    out.close()
    pure.close()
    reopened = fitz.open(output_tmp)
    geometry = verify_image_geometry(reopened, image_registry)
    source_mask_checks=[]
    for item in receipt.get('source_masks',[]):
        # Source clips are inherited through the shared A4 Form, while all new
        # gap explanations are omitted. A one-point inset avoids clip antialias.
        rect=fitz.Rect(item['rect'])+(1,1,-1,-1)
        pix=reopened[item['book_page']+3].get_pixmap(clip=rect,alpha=False)
        if min(pix.samples,default=255)!=255:
            raise ValueError('An obsolete red-answer source region reappeared: '+item['key'])
        source_mask_checks.append({'key':item['key'],'rect':item['rect'],'painted_region_blank':True})
    reopened_pure = fitz.open(pure_tmp)
    pure_geometry = verify_image_geometry(reopened_pure, image_registry)
    # Readers see a complete, validated file rather than a partially saved PDF.
    output_tmp.replace(output)
    pure_tmp.replace(pure_output)
    report = {"passed": True, "answer_pdf": str(answer_pdf.resolve()),
              "answer_sha256": source_hash, "receipt": str(receipt_path.resolve()),
              "receipt_sha256": sha256(receipt_path),
              "recovery_script_sha256": sha256(Path(__file__)),
              "output": str(output.resolve()), "output_sha256": sha256(output),
              "pure_source": str(pure_output.resolve()),
              "pure_source_sha256": sha256(pure_output),
              "pages": 128, "book_pages": 108, "bands_recovered": len(form_checks),
              "new_notes_omitted": len(receipt["answers"]),
              "local_patches_retained": len(receipt.get("local_replacements", [])),
              "source_answer_exclusions_retained":len(source_mask_checks),
              "source_answer_exclusion_checks":source_mask_checks,
              "footer_policy": "Original footer copied back to its source rectangle.",
              "band_policy": "Every receipt band matched and validated at 1:1; their shared identity-transform original A4 Form imported once to avoid clip-edge rasterization changes.",
              "reuse_policy": "Only the original source of the validated band Forms copied; new note Forms never imported as painted content. Original scan background is retained, without white masks.",
              "pure_source_policy": "Original JPEG bytes matched by SHA-256 and inserted at receipt.source_original_images exact rectangles.",
              "geometry": geometry, "pure_geometry": pure_geometry,
              "band_forms": form_checks}
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2))
    reopened.close()
    reopened_pure.close()
    source.close()
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("answer_pdf", type=Path)
    parser.add_argument("--receipt", type=Path,
                        default=ROOT / "detailed_layout/current_release.json")
    parser.add_argument("--output", type=Path,
                        default=ROOT / "recovered/annotated_a4_128.pdf")
    parser.add_argument("--pure-output", type=Path,
                        default=ROOT / "recovered/pure_source_128.pdf")
    parser.add_argument("--report", type=Path)
    parser.add_argument("--skip-hash-check", action="store_true",
                        help="Only for controlled local diagnostics.")
    args = parser.parse_args()
    report = recover(args.answer_pdf, args.receipt, args.output, args.pure_output,
                     args.report or args.output.parent / "concise_recovery_report.json",
                     verify_hash=not args.skip_hash_check)
    print(json.dumps({k: report[k] for k in
                      ("passed", "pages", "bands_recovered", "new_notes_omitted",
                       "local_patches_retained", "output", "pure_source", "geometry")},
                     ensure_ascii=False))


if __name__ == "__main__":
    main()
